//! On a moved library, an older build's `oculus docs` recreates `agents/` at
//! the top and points the subjects' links at it: the next launch sets the
//! folder aside and links the subjects to the state folder again.

use std::path::Path;

use super::fixture::{env, exists, file, library, read, FakeBroker, CODE};
use crate::library::migrate::state::stray::{set_aside, tidy};
use crate::library::migrate::state::{at_startup, run};
use crate::test_support::Scratch;

const BANNER: &str = "<!-- Generated by `oculus docs` from the binary's own help. Do not edit:\n";

/// What an older build's `oculus docs` leaves on a moved library.
#[cfg(unix)]
fn older_docs_ran(dir: &Path) {
    file(
        dir,
        "agents/OCULUS-CLI.md",
        &format!("{BANNER}# The `oculus` CLI\n"),
    );
    file(dir, "agents/TASTE.md", "taste");
    file(
        dir,
        &format!("agents/memories/{CODE}/written-since.md"),
        "kept",
    );
    let link = dir.join(format!("courses/{CODE}/.oculus/agents/memories"));
    std::fs::remove_file(&link).unwrap();
    std::os::unix::fs::symlink(Path::new("../../../../agents/memories").join(CODE), &link).unwrap();
}

#[cfg(unix)]
#[test]
fn an_older_builds_agents_folder_is_set_aside_whole_and_the_links_come_back() {
    let dir = library("state-move-stray");
    run(&dir, &env(&FakeBroker::default())).unwrap();
    older_docs_ran(&dir);

    tidy(&dir, "2026-11-27");
    assert!(!exists(&dir, "agents"), "gone from My Drive");
    let aside = ".oculus/stray-agents-2026-11-27";
    assert_eq!(read(&dir, &format!("{aside}/TASTE.md")), "taste");
    assert_eq!(
        read(&dir, &format!("{aside}/memories/{CODE}/written-since.md")),
        "kept"
    );
    let link = dir.join(format!("courses/{CODE}/.oculus/agents/memories"));
    assert_eq!(
        std::fs::read_link(&link).unwrap(),
        Path::new("../../../../.oculus/agents/memories").join(CODE)
    );
    assert_eq!(
        read(
            &dir,
            &format!("courses/{CODE}/.oculus/agents/memories/MEMORY.md")
        ),
        "# mine\n"
    );

    // Again, on another launch the same day: a name of its own, nothing merged.
    older_docs_ran(&dir);
    tidy(&dir, "2026-11-27");
    assert!(exists(&dir, &format!("{aside}-2/TASTE.md")));
    assert!(exists(&dir, &format!("{aside}/TASTE.md")));

    // The launch check does the same.
    older_docs_ran(&dir);
    at_startup(&dir).unwrap();
    assert!(!exists(&dir, "agents"));
}

#[test]
fn an_agents_folder_of_the_students_own_is_left_alone() {
    let dir = Scratch::new("state-move-stray-own");
    std::fs::create_dir_all(dir.join(".oculus")).unwrap();
    file(&dir, "agents/plan.md", "my agents essay");
    file(&dir, "agents/OCULUS-CLI.md", "notes I typed");
    assert_eq!(set_aside(&dir, "2026-11-27").unwrap(), None);
    assert_eq!(read(&dir, "agents/plan.md"), "my agents essay");
}

/// Every launch relinks: on thirty subjects already linked it costs a few
/// syscalls each.
#[test]
fn relinking_thirty_subjects_is_cheap_enough_for_every_launch() {
    let dir = Scratch::new("state-move-relink-cost");
    std::fs::create_dir_all(dir.join(".oculus/agents")).unwrap();
    for n in 0..30 {
        std::fs::create_dir_all(dir.join(format!("courses/SUBJ{n}_2026"))).unwrap();
    }
    tidy(&dir, "2026-11-27");
    let started = std::time::Instant::now();
    for _ in 0..10 {
        tidy(&dir, "2026-11-27");
    }
    let each = started.elapsed() / 10;
    eprintln!("relinking 30 subjects took {each:?}");
    assert!(each < std::time::Duration::from_millis(50), "{each:?}");
}
