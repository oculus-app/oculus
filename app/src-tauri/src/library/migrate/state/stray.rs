//! On a moved library, what an older build's `oculus docs` undoes: it writes
//! a fresh `agents/` at the top (it knows no state folder) and points each
//! subject's links back at it. At every launch an `agents/` at the top that
//! carries the CLI doc only `oculus docs` writes is set aside whole into the
//! state folder under a dated name (never merged, never deleted), and the
//! subjects are linked to `.oculus/agents/` again. An `agents/` without that
//! doc is the student's and is left alone.

use std::path::{Path, PathBuf};

use crate::agents::CLI_DOC_NAME;
use crate::library::paths::state_dir;

/// The first line `render_cli_docs` writes, in every build since the CLI
/// doc existed.
const CLI_DOC_BANNER: &str = "<!-- Generated by `oculus docs`";

/// The top-level folder an older build recreates.
const OLD_AGENTS: &str = "agents";

/// Sets a stray `agents/` aside and relinks the subjects. Failures are
/// logged: the library is usable either way.
pub fn tidy(data_dir: &Path, today: &str) {
    match set_aside(data_dir, today) {
        Ok(Some(to)) => elog!(
            "[oculus] an older build's agents/ at the top of the library was set aside in {}",
            to.display()
        ),
        Ok(None) => {}
        Err(e) => elog!("[oculus] could not set the stray agents/ aside: {e}"),
    }
    if crate::agents::agents_dir(data_dir).is_dir() {
        if let Err(e) = crate::agents::link_all(data_dir) {
            elog!("[oculus] could not relink the subjects' agent folders: {e}");
        }
    }
}

/// `agents/` at the top, when it is the app's own, renamed in one step to
/// `.oculus/stray-agents-<today>` (or `-2`, `-3`… when taken).
pub fn set_aside(data_dir: &Path, today: &str) -> Result<Option<PathBuf>, String> {
    let stray = data_dir.join(OLD_AGENTS);
    let is_dir = std::fs::symlink_metadata(&stray).is_ok_and(|m| m.is_dir());
    if !is_dir || !generated(&stray) {
        return Ok(None);
    }
    let state = state_dir(data_dir);
    let base = format!("stray-agents-{today}");
    let to = (1..)
        .map(|n| match n {
            1 => state.join(&base),
            n => state.join(format!("{base}-{n}")),
        })
        .find(|p| std::fs::symlink_metadata(p).is_err())
        .expect("an unused name");
    std::fs::rename(&stray, &to)
        .map_err(|e| format!("rename {} to {}: {e}", stray.display(), to.display()))?;
    Ok(Some(to))
}

/// The CLI doc `oculus docs` writes, with its banner, is in the folder.
fn generated(agents: &Path) -> bool {
    std::fs::read_to_string(agents.join(CLI_DOC_NAME)).is_ok_and(|t| t.starts_with(CLI_DOC_BANNER))
}
